func topFindings(findings []store.AuditFinding, limit int) []store.AuditFinding {
	if limit <= 0 || len(findings) == 0 {
		return nil
	}
	out := make([]store.AuditFinding, len(findings))
	copy(out, findings)
	// already sorted by severity in store query; slice top N
	if len(out) > limit {
		out = out[:limit]
	}
	return out
}

func qualityFindings(findings []store.AuditFinding, limit int) []store.AuditFinding {
	var out []store.AuditFinding
	for _, f := range findings {
		switch f.Category {
		case "tech_debt", "reliability", "maintainability", "test_gap", "performance", "code_quality":
			out = append(out, f)
		default:
			if f.Source == "tech_debt" || f.Source == "reliability" || f.Source == "maintainability" || f.Source == "test_gap" || f.Source == "performance" || f.Source == "graph" {
				out = append(out, f)
			}
		}
	}
	if len(out) > limit {
		out = out[:limit]
	}
	return out
}

func isSecretFinding(f store.AuditFinding) bool {
	if f.Source == "gitleaks" || f.Category == "secret" {
		return true
	}
	return strings.Contains(strings.ToLower(f.Title), "secret")
}

func isHighSeverity(severity string) bool {
	switch strings.ToLower(severity) {
	case "critical", "high":
		return true
	default:
		return false
	}
}

func graphSummaryFromAudit(audit store.AuditRequest) string {
	if len(audit.SummaryJSON) == 0 {
		return ""
	}
	var summary map[string]any
	if err := json.Unmarshal(audit.SummaryJSON, &summary); err != nil {
		return ""
	}
	nodes, _ := summary["graph_nodes"].(float64)
	edges, _ := summary["graph_edges"].(float64)
	if nodes <= 0 {
		return ""
	}
	return fmt.Sprintf("Repository map generated: %.0f nodes, %.0f edges. Review disconnected-code graph findings in the audit detail.", nodes, edges)
}

// ReportContainsRawSecrets returns true if markdown appears to contain raw secret material.
func ReportContainsRawSecrets(body string) bool {
	sanitized := issues.SanitizeSecretEvidence(body)
	return sanitized != strings.TrimSpace(body) && strings.Contains(body, "[REDACTED]")
}
